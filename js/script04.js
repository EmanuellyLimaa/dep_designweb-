let dia = prompt("Sendo: 1 Domingo e 7: Sábado\nDigite o dia da semana ");
if(dia == 1){
    alert("Hoje é domigo");
}else if (dia == 2){
    alert("Hoje é segunda");
}else if (dia == 3){
    alert("Hoje é terça");
}else if (dia == 4){
    alert("Hoje é quarta");
}else if (dia == 5){
    alert("Hoje é quinta");
}else if (dia == 6){
    alert("Hoje é sexta");
}else if (dia == 7){
    alert("Hoje é sábado");
}else{
    alert("Dia inválido");
}